"""Inspect a folder and propose rules for what is actually in it."""

from __future__ import annotations

from collections import Counter
from dataclasses import dataclass
from pathlib import Path

# Extension families we know how to name. Anything else is grouped under its
# own extension so the user still gets a usable starting point.
FAMILIES: list[tuple[str, str, set[str]]] = [
    ("Images", "Images", {".jpg", ".jpeg", ".png", ".gif", ".webp", ".heic", ".svg", ".bmp", ".tiff"}),
    ("Documents", "Documents", {".pdf", ".doc", ".docx", ".odt", ".txt", ".md", ".rtf", ".epub"}),
    ("Spreadsheets", "Documents/Spreadsheets", {".xls", ".xlsx", ".csv", ".tsv", ".ods"}),
    ("Presentations", "Documents/Presentations", {".ppt", ".pptx", ".odp", ".key"}),
    ("Archives", "Archives", {".zip", ".tar", ".gz", ".bz2", ".xz", ".rar", ".7z"}),
    ("Installers", "Installers", {".dmg", ".pkg", ".exe", ".msi", ".deb", ".rpm", ".appimage"}),
    ("Video", "Video", {".mp4", ".mkv", ".mov", ".avi", ".webm", ".m4v"}),
    ("Audio", "Audio", {".mp3", ".wav", ".flac", ".m4a", ".ogg", ".aac"}),
    ("Code", "Code", {".py", ".js", ".ts", ".java", ".c", ".cpp", ".go", ".rs", ".rb", ".sh"}),
    ("Fonts", "Fonts", {".ttf", ".otf", ".woff", ".woff2"}),
]

SCREENSHOT_PREFIXES = ("screenshot", "screen shot", "ekran", "capture")


@dataclass
class Suggestion:
    name: str
    target: str
    count: int
    extensions: list[str] | None = None
    patterns: list[str] | None = None

    def to_yaml(self) -> str:
        lines = [f"  - name: {self.name}", f"    target: {self.target}"]
        if self.patterns:
            rendered = ", ".join(f'"{p}"' for p in self.patterns)
            lines.append(f"    patterns: [{rendered}]")
        if self.extensions:
            rendered = ", ".join(e.lstrip(".") for e in self.extensions)
            lines.append(f"    extensions: [{rendered}]")
        return "\n".join(lines)


def scan(source: Path, recursive: bool = False) -> list[Suggestion]:
    """Return rule suggestions ordered from most to least specific."""
    if not source.is_dir():
        raise NotADirectoryError(f"Source directory not found: {source}")

    paths = [
        p
        for p in (source.rglob("*") if recursive else source.iterdir())
        if p.is_file() and not p.name.startswith(".")
    ]

    screenshots = [p for p in paths if p.name.lower().startswith(SCREENSHOT_PREFIXES)]
    remaining = [p for p in paths if p not in set(screenshots)]
    counts = Counter(p.suffix.lower() for p in remaining if p.suffix)

    suggestions: list[Suggestion] = []

    if screenshots:
        suggestions.append(
            Suggestion(
                name="Screenshots",
                target="Images/Screenshots",
                count=len(screenshots),
                patterns=["screenshot*", "Screen Shot*", "Ekran*"],
            )
        )

    claimed: set[str] = set()
    for name, target, extensions in FAMILIES:
        present = sorted(ext for ext in extensions if counts.get(ext))
        if not present:
            continue
        total = sum(counts[ext] for ext in present)
        suggestions.append(
            Suggestion(name=name, target=target, count=total, extensions=present)
        )
        claimed.update(present)

    # Anything left over that shows up often enough to be worth a rule.
    leftovers = [(ext, n) for ext, n in counts.items() if ext not in claimed and n >= 2]
    for ext, n in sorted(leftovers, key=lambda pair: -pair[1]):
        label = ext.lstrip(".").upper()
        suggestions.append(
            Suggestion(name=f"{label} files", target=label, count=n, extensions=[ext])
        )

    return suggestions


def to_config(source: Path, suggestions: list[Suggestion]) -> str:
    """Render suggestions as a complete, ready-to-use config file."""
    if not suggestions:
        return f"source: {source}\nrules: []\n"

    body = "\n\n".join(s.to_yaml() for s in suggestions)
    return (
        f"source: {source}\n"
        "recursive: false\n"
        "on_conflict: rename\n\n"
        "# Generated by 'foldersort suggest'. The first matching rule wins.\n"
        "rules:\n"
        f"{body}\n"
    )
